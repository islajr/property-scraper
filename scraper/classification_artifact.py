"""Freeze and validate reviewed previews before any backfill database writes."""
from contextlib import contextmanager
from dataclasses import dataclass
from datetime import datetime
import hashlib
import json
from pathlib import Path
import tempfile

from scraper import property_types
from scraper.property_types import FIELDS, STATUSES, TYPES, VERSION


class ReviewError(ValueError):
    """An artifact, target, or operation does not match the reviewed contract."""


def database_fingerprint(conn):
    dsn = conn.get_dsn_parameters()
    return hashlib.sha256(json.dumps({key: dsn.get(key) for key in ('host','port','dbname')},
                                    sort_keys=True).encode()).hexdigest()


def classifier_fingerprint():
    return hashlib.sha256(Path(property_types.__file__).read_bytes()).hexdigest()


def _validate_record(record, previous_id):
    if not isinstance(record, dict):
        raise ReviewError('Preview rows must be JSON objects')
    lid = record.get('id')
    if type(lid) is not int or lid <= previous_id:
        raise ReviewError('Preview listing IDs must be positive, unique and increasing')
    if not isinstance(record.get('source'), str) or not record['source']:
        raise ReviewError('Preview row lacks a source')
    if record.get('listing_status') not in ('ACTIVE', 'REMOVED'):
        raise ReviewError('Preview row has an invalid lifecycle state')
    version = record.get('row_version')
    if not isinstance(version, str) or not version.isdecimal():
        raise ReviewError('Preview row lacks a PostgreSQL row version')
    for field in ('previous', 'proposed'):
        if not isinstance(record.get(field), dict) or set(record[field]) != set(FIELDS):
            raise ReviewError('Preview metadata shape differs from this classifier')
    new = record['proposed']
    if new['property_type_version'] != VERSION:
        raise ReviewError('Preview uses another classifier version; regenerate it')
    status = new['property_type_status']
    if status not in STATUSES or status == 'LEGACY_UNREVIEWED':
        raise ReviewError('Proposed classification has an invalid state')
    if status == 'CLASSIFIED':
        code = new['property_type']
        if not isinstance(code, str) or code not in TYPES:
            raise ReviewError('Proposed type is outside the vocabulary')
        definition = TYPES[code]
        if new['property_category'] != definition.category or new['property_type_family'] != definition.family:
            raise ReviewError('Proposed category/family differs from its vocabulary entry')
    elif new['property_type'] is not None:
        raise ReviewError('An unresolved classification must have a NULL type')
    evidence = new['property_type_evidence']
    if not isinstance(evidence, dict) or not isinstance(evidence.get('matches'), list):
        raise ReviewError('Proposed classification lacks structured evidence')
    for value, required in ((record['previous']['property_type_classified_at'], False),
                            (new['property_type_classified_at'], True)):
        if value is None and not required:
            continue
        try:
            classified = datetime.fromisoformat(value)
            if classified.utcoffset() is None:
                raise ValueError
        except (TypeError, ValueError):
            raise ReviewError('Classification metadata lacks a timezone-aware decision time') from None
    return lid


@dataclass
class Artifact:
    stream: object
    summary: dict

    def records(self):
        self.stream.seek(0)
        for line in self.stream:
            yield json.loads(line)


@contextmanager
def reviewed_preview(path):
    """Stage a private immutable copy: file changes after validation cannot race apply.

    Legacy v1 previews are supported; each proposed decision is also recomputed
    from the locked current row before applying. New previews additionally bind
    the exact classifier source hash. Hashes detect changes, not author approval.
    """
    path = Path(path)
    try:
        summary = json.loads(path.with_suffix('.summary.json').read_text())
        if not isinstance(summary, dict) or not isinstance(summary.get('counts'), dict):
            raise ReviewError('Preview summary must contain its row counts')
        if summary.get('read_only') is not True or summary.get('rule_version') != VERSION:
            raise ReviewError('Use a read-only preview generated by this classifier version')
        if summary.get('classifier_sha256', classifier_fingerprint()) != classifier_fingerprint():
            raise ReviewError('Classifier source changed since preview; regenerate it')
        if not isinstance(summary.get('database_fingerprint'), str):
            raise ReviewError('Preview lacks its database fingerprint')
        digest, count, last_id = hashlib.sha256(), 0, 0
        with tempfile.TemporaryFile(mode='w+b') as frozen:
            with path.open('rb') as original:
                while line := original.readline(1_048_577):
                    if len(line) > 1_048_576:
                        raise ReviewError('Preview row exceeds the supported size')
                    digest.update(line)
                    record = json.loads(line)
                    last_id = _validate_record(record, last_id)
                    frozen.write(line)
                    count += 1
            if digest.hexdigest() != summary.get('report_sha256'):
                raise ReviewError('Preview checksum does not match its summary')
            if count != summary.get('counts', {}).get('scanned', 0):
                raise ReviewError('Preview row count does not match its summary')
            frozen.seek(0)
            yield Artifact(frozen, summary)
    except (OSError, json.JSONDecodeError, UnicodeError):
        raise ReviewError('Cannot read a valid preview and companion summary') from None
